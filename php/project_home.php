<h1>GRC Risk and Compliance Tracking System</h1>

<p>
This system is designed to support basic Governance, Risk, and Compliance (GRC) tracking
for NorthBridge Financial Services. It allows users to manage risks, controls, compliance
requirements, and audit results in a structured and organized way.
</p>

<h2>Available Features</h2>

<ul>
    <li><strong>Display Risks:</strong> View all risks along with their assigned employees and departments.</li>
    <li><strong>Audit Results:</strong> Review how controls performed during audits.</li>
    <li><strong>Add Risk:</strong> Insert a new risk into the system.</li>
    <li><strong>Add Control:</strong> Insert a new control into the system.</li>
    <li><strong>Search Risks:</strong> Search risks by their risk level (High, Medium, Low).</li>
</ul>

<p>
Use the navigation menu above to access each feature.
</p>

